"""
lexicon.py
----------
Closed-class Hindi word lists and regexes used by the rule-based ellipsis detectors.

Hindi is head-final (SOV), marks case with postpositions (ने, को, से, में ...),
has split-ergative alignment (ने in perfective transitive clauses), and rich verb
agreement. Most ellipsis cues in Hindi are therefore found in:
  * postpositions/case markers (remnants of an elided clause keep their case),
  * focus particles (भी, ही, तो) and negation (नहीं, न) that "strand" remnants,
  * clause-final verb/auxiliary position (a missing verb = a missing clause-final slot),
  * agreement morphology (हूँ, -ूँगा, -ोगे, -िए) that identifies a null subject.
Extend these lists freely - they are the main knob for precision/recall.
"""
import re
