# --------------------------------------------------------------------------- #
# Tokenisation
# --------------------------------------------------------------------------- #
# Devanagari block is U+0900-U+097F, but the danda (U+0964) and double danda
# (U+0965) are punctuation, so they are excluded from "word" characters.
_WORD = r"[\u0900-\u0963\u0966-\u097F\u200c\u200d]+"
TOKEN_RE = re.compile(rf"{_WORD}|[A-Za-z]+|\d+(?:[.,]\d+)*|[^\s]")
SENT_END = {"।", "॥", "?", "!", "|", "."}
SENT_SPLIT_RE = re.compile(r"(?<=[।॥?!|])\s+|\n+")
DEVANAGARI_RE = re.compile(r"[\u0900-\u097F]")


def normalize(text: str) -> str:
    """NFC-normalise, unify common spelling variants, squeeze spaces."""
    text = unicodedata.normalize("NFC", text)
    text = text.replace("\u200b", "")            # zero-width space
    text = re.sub(r"[ \t]+", " ", text)
    return text.strip()


def tokenize(sentence: str):
    return TOKEN_RE.findall(sentence)


def is_punct(tok: str) -> bool:
    return not any(ch.isalnum() for ch in tok)


def devanagari_ratio(text: str) -> float:
    letters = [c for c in text if not c.isspace()]
    if not letters:
        return 0.0
    return sum(1 for c in letters if DEVANAGARI_RE.match(c)) / len(letters)


